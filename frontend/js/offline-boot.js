/*
 * FTC2 — تهيئة النسخة المحلية قبل أي منطق آخر في البرنامج
 * -------------------------------------------------------------
 * يُحمَّل أول script غير المؤجَّل في app.html، فينفَّذ قبل كل الوحدات الأخرى
 * (جميعها defer). مهمته الوحيدة ضمان أن يبدأ البرنامج مباشرة في وضع التشغيل
 * المحلي:
 *   1) تخزين كود ترخيص ثابت في localStorage إن لم يكن موجوداً، فيتجاوز boot.js
 *      شاشة «تفعيل البرنامج» ويذهب لتحقق على الخادم المحلي (الذي يقبله دائماً
 *      من أول استخدام على هذا الجهاز).
 *
 * لا يغيّر أي إعداد آخر: لا وضع عدم اتصال يدوي (manualOfflineMode) — كل طلبات
 * /api تذهب إلى الخادم المحلي على 127.0.0.1:17532 وتعمل فعلياً.
 */
(function () {
  try {
    var KEY = 'appLicenseKeyV1';
    var VALUE = 'FTC2LOCALOFFLINE';
    if (!localStorage.getItem(KEY)) {
      localStorage.setItem(KEY, VALUE);
    }
  } catch (e) {
    console.warn('[OfflineBoot] تعذّر تخزين مفتاح الترخيص المبدئي:', e);
  }
})();
